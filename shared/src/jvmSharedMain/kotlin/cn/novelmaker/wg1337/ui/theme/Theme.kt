/**
 * NovelMaker Material3 主题（Android / Windows 共用）
 * @param darkTheme 是否使用暗色主题
 * @param dynamicColor 是否启用动态取色（仅 Android 12+ 支持）
 */
@Composable
fun NovelMakerTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = true,
    content: @Composable () -> Unit
) {
    val colorScheme = platformDynamicColorScheme(darkTheme, dynamicColor)
        ?: if (darkTheme) DarkColorScheme else LightColorScheme

    // 平台系统栏定制（Android 实际处理状态栏，Windows 为空实现）
    PlatformSystemBarsEffect(darkTheme)

    MaterialTheme(
        colorScheme = colorScheme,
        content = content
    )
}
